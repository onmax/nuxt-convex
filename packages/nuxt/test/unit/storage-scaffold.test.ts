import { describe, expect, it } from 'vitest'
import { buildStorageFunctions, isUnguardedStorageScaffold } from '../../src/internal/storage-scaffold'

describe('storage scaffold', () => {
  const contents = buildStorageFunctions('../_generated/server')

  it('requires a signed-in user in every function', () => {
    expect(contents).toContain(`from '../_generated/server'`)
    expect(contents).toContain('await ctx.auth.getUserIdentity()')
    expect(contents).toContain('ownership')
    expect(contents.match(/await requireIdentity\(ctx\)/g)).toHaveLength(3)
  })

  it('flags scaffolds from older versions', () => {
    expect(isUnguardedStorageScaffold(contents)).toBe(false)
    expect(isUnguardedStorageScaffold(`// Auto-generated by nuxt-convex - feel free to customize\nexport const remove = mutation(...)`)).toBe(true)
    expect(isUnguardedStorageScaffold('export const mine = 1')).toBe(false)
  })
})
